#!/usr/bin/env node

import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const repoRoot = process.cwd();
const specsDir = path.join(repoRoot, 'specs');
const currentWorkPath = path.join(specsDir, 'CURRENT-WORK.md');
const reconciliationPath = path.join(specsDir, 'RECONCILIATION.md');
const featureStatePath = path.join(repoRoot, '.specify', 'feature.json');
const overviewPath = path.join(specsDir, 'OVERVIEW.md');
const backlogPath = path.join(specsDir, 'BACKLOG.md');

function run(command) {
  return execSync(command, {
    cwd: repoRoot,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

function safeRun(command, fallback = '') {
  try {
    return run(command);
  } catch {
    return fallback;
  }
}

function readText(filePath, fallback = '') {
  if (!existsSync(filePath)) {
    return fallback;
  }

  return readFileSync(filePath, 'utf8');
}

function getActiveFeatureDir() {
  try {
    const state = JSON.parse(readText(featureStatePath, '{}'));
    if (typeof state.feature_directory === 'string' && state.feature_directory.trim() !== '') {
      return path.resolve(repoRoot, state.feature_directory);
    }
  } catch {
    return null;
  }

  return null;
}

function getActiveFeatureLabel(featureDir) {
  if (!featureDir) {
    return 'No active spec selected in `.specify/feature.json`.';
  }

  return path.relative(repoRoot, featureDir).replaceAll(path.sep, '/');
}

function getTasksPath(featureDir) {
  if (!featureDir) {
    return null;
  }

  const tasksPath = path.join(featureDir, 'tasks.md');
  return existsSync(tasksPath) ? tasksPath : null;
}

function getUncheckedTaskLines(tasksPath) {
  if (!tasksPath) {
    return [];
  }

  return readText(tasksPath)
    .split(/\r?\n/u)
    .map((line) => line.trim())
    .filter((line) => line.startsWith('- [ ]'));
}

function getNextSpecTask(featureDir) {
  const tasksPath = getTasksPath(featureDir);
  if (!tasksPath) {
    return 'Active spec has no `tasks.md`; run the spec-kit tasks phase or review `specs/OVERVIEW.md`.';
  }

  const [nextTask] = getUncheckedTaskLines(tasksPath);
  if (!nextTask) {
    return 'No unchecked tasks in active spec; review `specs/OVERVIEW.md` Current Priority and `specs/BACKLOG.md`.';
  }

  return nextTask.replace(/^- \[ \]\s*/u, '');
}

function getBacklogItemCount() {
  return readText(backlogPath)
    .split(/\r?\n/u)
    .filter((line) => /^\| BACKLOG-\d+ \|/u.test(line))
    .length;
}

function getOverviewPriorityLines() {
  const lines = readText(overviewPath).split(/\r?\n/u);
  const start = lines.findIndex((line) => line.trim() === '## Current Priority');
  if (start === -1) {
    return '- See `specs/OVERVIEW.md`.';
  }

  const priorities = [];
  for (const line of lines.slice(start + 1)) {
    if (line.startsWith('## ')) {
      break;
    }
    if (/^\d+\.\s/u.test(line.trim())) {
      priorities.push(line.trim());
    }
  }

  return priorities.length > 0 ? priorities.join('\n') : '- See `specs/OVERVIEW.md`.';
}

function getWorktreeLines() {
  const raw = safeRun('git status --short --untracked-files=all', '');
  return raw
    .split(/\r?\n/u)
    .map((line) => line.trimEnd())
    .filter(Boolean)
    .filter((line) => !line.includes('specs/CURRENT-WORK.md'))
    .filter((line) => !line.includes('specs/RECONCILIATION.md'))
    .sort((left, right) => left.localeCompare(right));
}

function buildCurrentWork() {
  const branch = safeRun('git branch --show-current', '(unknown)');
  const head = safeRun('git rev-parse --short HEAD', '(unknown)');
  const featureDir = getActiveFeatureDir();
  const featureLabel = getActiveFeatureLabel(featureDir);
  const nextTask = getNextSpecTask(featureDir);
  const worktreeLines = getWorktreeLines();

  const worktreeSection =
    worktreeLines.length === 0
      ? '- Clean worktree (excluding continuity files).'
      : worktreeLines.map((line) => `- ${line}`).join('\n');

  return `# Current Work

Generated by \`pnpm continuity:update\`.

## Repository
- Branch: \`${branch}\`
- HEAD: \`${head}\`

## Active Spec
- ${featureLabel}

## Next Spec Task
- ${nextTask}

## Current Priority
${getOverviewPriorityLines()}

## Working Tree
${worktreeSection}
`;
}

function buildReconciliation() {
  const branch = safeRun('git branch --show-current', '(unknown)');
  const head = safeRun('git rev-parse HEAD', '(unknown)');
  const featureDir = getActiveFeatureDir();
  const featureLabel = getActiveFeatureLabel(featureDir);
  const openTasks = getUncheckedTaskLines(getTasksPath(featureDir)).length;
  const changedFiles = getWorktreeLines().length;

  return `# Reconciliation

Generated by \`pnpm continuity:update\`.

## Snapshot
- Branch: \`${branch}\`
- HEAD: \`${head}\`
- Active spec: ${featureLabel}
- Open tasks in active spec: ${openTasks}
- Backlog items: ${getBacklogItemCount()}
- Non-continuity working-tree entries: ${changedFiles}

## Intent
- Keep a lightweight, committed continuity snapshot in the repo.
- Use spec-kit artifacts as the planning source of truth: active spec tasks, \`specs/OVERVIEW.md\`, and \`specs/BACKLOG.md\`.
`;
}

mkdirSync(specsDir, { recursive: true });
writeFileSync(currentWorkPath, buildCurrentWork(), 'utf8');
writeFileSync(reconciliationPath, buildReconciliation(), 'utf8');
